export type MessageKey = keyof typeof englishMessages;
export type Messages = Record<MessageKey, string>;
export const spanishMessages = Object.fromEntries(Object.keys(englishMessages).map(key => [key, key])) as Messages;

export type Locale = 'es' | 'en';
export function translate(message: string, locale: Locale = 'es', ...values: (string | number)[]): string {
  const dictionary: Messages = locale === 'en' ? englishMessages : spanishMessages;
  const template = Object.hasOwn(dictionary, message) ? dictionary[message as MessageKey] : message;
  return template.replace(/\{(\d+)\}/g, (match, index: string) => String(values[Number(index)] ?? match));
}
